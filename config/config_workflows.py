# config_workflows.py - Workflow definitions
"""
Default workflow definitions shipped with the bot.

Workflows are sequences of steps the scheduler runs on an interval (or on
manual trigger). Users can edit / add / remove workflows via the WebUI;
overrides land in config/user_workflows.json and replace the in-code
defaults completely on next reload.

WF dict shape:
    "<slug>": {
        "name":                  short display name
        "description":           one-liner shown in WebUI
        "order":                 sort key for UI list (int, low = top)
        "enabled_default":       auto-enable on bot startup (bool)
        "inactive":              hide from scheduler entirely (bool, user toggle)
        "interval_s":            seconds between auto runs
        "interval_variance_pct": +/- random variance on interval (None = use global)
        "log_level":             "FULL"|"TXT"|"UI" or None = use global
        "log_level_step":        per-step exec log level    or None = use global
        "log_level_busy":        postponed/busy log level    or None = use global
        "ignore_action_lock":    override: run even while a feature holds the
                                 action lock (bool, default False). Use only
                                 for tiny defensive WFs (e.g. close-popup-if-
                                 visible). Does NOT preempt another running WF.
        "steps":                 list[step-dict]
    }

Step types (common keys: "type", "_disabled", "sleep_after"):
    tap_roi          random tap inside ROI    -> roi=[x1,y1,x2,y2], jitter
    tap_xy           fixed coordinate tap     -> x, y, jitter
    swipe            drag A->B with duration  -> x1, y1, x2, y2, duration_ms
    click_template   template match + tap     -> template, roi, threshold,
                                                 offset_x, offset_y, jitter,
                                                 optional, use_prev_screenshot,
                                                 clicks, click_interval_s
    click_rotating   rotated template match   -> template, roi, threshold,
                                                 rotations, offset_x, offset_y,
                                                 jitter, optional,
                                                 use_prev_screenshot, clicks,
                                                 click_interval_s, log_mode
                                                 (log_mode: both|hit_only|
                                                  miss_only|none)
    wait             sleep                    -> seconds
    rainbow_check    detect Rainbow Floor     -> roi, sat_min, val_min,
                                                 min_sat_pixels, min_hue_buckets,
                                                 min_pixels_per_bucket, hue_buckets,
                                                 min_hue_entropy,
                                                 optional, use_prev_screenshot
    call_workflow    run another workflow     -> target (slug; may be inactive)
    hold_and_wiggle  chained swipes in ROI    -> roi, duration_s, step_ms, max_step_px
"""
